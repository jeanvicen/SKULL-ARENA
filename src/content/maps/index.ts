export function getMap(id: string): MapDef {
  return MAPS.find((m) => m.id === id) ?? MAPS[0]!;
}

export function mapsForMode(mode: string): MapDef[] {
  return MAPS.filter((m) => (m.modes as string[]).includes(mode));
}
